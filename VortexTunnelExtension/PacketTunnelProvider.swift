import Foundation
import NetworkExtension
import Darwin
#if canImport(Libbox)
import Libbox
#endif

/// NetworkExtension Packet Tunnel Provider managing the virtual interface and sing-box core handoff
public final class PacketTunnelProvider: NEPacketTunnelProvider, @unchecked Sendable {

    // MARK: - Runtime Properties

    private var tunFd: Int32 = -1
    private var isRunning: Bool = false
    private var txBytes: Int64 = 0
    private var rxBytes: Int64 = 0
    private var statsTask: Task<Void, Never>?

    #if canImport(Libbox)
    private var boxService: LibboxBoxService?
    private var platformAdapter: LibboxPlatformAdapter?
    #endif

    // MARK: - Tunnel Lifecycle

    public override func startTunnel(
        options: [String: NSObject]?,
        completionHandler: @escaping (Error?) -> Void
    ) {
        // 1. Read sing-box configuration generated by Host App in shared container
        let configJSON = AppGroup.loadSingBoxConfig()
        NSLog("[VortexExtension] Loaded sing-box configuration: %lu bytes", UInt(configJSON?.count ?? 0))
        let mtu = AppGroup.getMTU()

        // 2. Configure Virtual Interface Settings (172.19.0.1/30)
        let settings = NEPacketTunnelNetworkSettings(tunnelRemoteAddress: "127.0.0.1")
        settings.mtu = NSNumber(value: mtu)

        // IPv4 configuration
        let ipv4Settings = NEIPv4Settings(
            addresses: ["172.19.0.1"],
            subnetMasks: ["255.255.255.252"]
        )
        ipv4Settings.includedRoutes = [NEIPv4Route.default()]

        // Exclude private LAN routes to prevent capturing local network traffic
        ipv4Settings.excludedRoutes = [
            NEIPv4Route(destinationAddress: "10.0.0.0", subnetMask: "255.0.0.0"),
            NEIPv4Route(destinationAddress: "172.16.0.0", subnetMask: "255.240.0.0"),
            NEIPv4Route(destinationAddress: "192.168.0.0", subnetMask: "255.255.0.0"),
            NEIPv4Route(destinationAddress: "127.0.0.0", subnetMask: "255.0.0.0")
        ]
        settings.ipv4Settings = ipv4Settings

        // DNS configuration
        let directDns = AppGroup.getDirectDNS()
        let dnsSettings = NEDNSSettings(servers: ["172.19.0.2", directDns])
        dnsSettings.matchDomains = [""] // Intercept all DNS requests
        settings.dnsSettings = dnsSettings

        // 3. Apply settings to NetworkExtension framework
        setTunnelNetworkSettings(settings) { [weak self] error in
            guard let self = self else { return }

            if let error = error {
                completionHandler(error)
                return
            }

            self.isRunning = true

            // 4. Extract utun socket file descriptor for Go sing-box core
            if let fd = self.packetFlow.value(forKeyPath: "socket.fileDescriptor") as? Int32, fd > 0 {
                self.tunFd = fd
                NSLog("[VortexExtension] Acquired utun file descriptor: %d", fd)
            } else {
                NSLog("[VortexExtension] utun fd extraction not available; using packetFlow fallback")
            }

            // 5. Initialize precompiled Libbox (sing-box core) if available
            #if canImport(Libbox)
            self.startLibboxService(configJSON: configJSON)
            #endif

            // 6. Start packet observation / read loop and background telemetry
            self.startPacketFlowLoop()
            self.startStatsUpdater()

            completionHandler(nil)
        }
    }

    #if canImport(Libbox)
    private func startLibboxService(configJSON: String?) {
        guard let config = configJSON, !config.isEmpty else {
            NSLog("[VortexExtension] No configuration JSON found in AppGroup")
            return
        }

        let containerPath = AppGroup.containerURL.path
        let setupOptions = LibboxSetupOptions()
        setupOptions.basePath = containerPath
        setupOptions.workingPath = containerPath
        setupOptions.tempPath = containerPath
        setupOptions.username = ""

        var setupError: NSError?
        LibboxSetup(setupOptions, &setupError)
        LibboxSetMemoryLimit(true) // Enforces 32MB memory cap for iOS NetworkExtension

        let adapter = LibboxPlatformAdapter(provider: self)
        self.platformAdapter = adapter

        var serviceError: NSError?
        if let service = LibboxNewService(config, adapter, &serviceError) {
            do {
                try service.start()
                self.boxService = service
                NSLog("[VortexExtension] Libbox sing-box core started successfully!")
            } catch {
                NSLog("[VortexExtension] Failed to start Libbox service: %@", error.localizedDescription)
            }
        } else if let err = serviceError {
            NSLog("[VortexExtension] Failed to create Libbox service: %@", err.localizedDescription)
        }
    }
    #endif

    public override func stopTunnel(
        with reason: NEProviderStopReason,
        completionHandler: @escaping () -> Void
    ) {
        isRunning = false
        tunFd = -1
        statsTask?.cancel()
        statsTask = nil

        #if canImport(Libbox)
        try? boxService?.close()
        boxService = nil
        platformAdapter = nil
        #endif

        NSLog("[VortexExtension] Tunnel stopped with reason: %ld", reason.rawValue)
        completionHandler()
    }

    // MARK: - IPC Communication (`sendProviderMessage`)

    public override func handleAppMessage(_ messageData: Data, completionHandler: ((Data?) -> Void)?) {
        guard let message = TunnelIPCMessage.decode(from: messageData) else {
            completionHandler?(nil)
            return
        }

        switch message.command {
        case .getStatus:
            let response: [String: Any] = [
                "status": isRunning ? "connected" : "disconnected"
            ]
            replyJSON(response, completionHandler: completionHandler)

        case .getStats:
            let memory = getMemoryUsageBytes()
            let response: [String: Any] = [
                "txBytes": txBytes,
                "rxBytes": rxBytes,
                "memoryBytes": memory
            ]
            replyJSON(response, completionHandler: completionHandler)

        case .reloadConfig, .reloadRules:
            // Re-read active config from shared container
            let newConfig = AppGroup.loadSingBoxConfig()
            NSLog("[VortexExtension] Reloaded configuration from AppGroup: %lu bytes", UInt(newConfig?.count ?? 0))

            #if canImport(Libbox)
            if let config = newConfig, let adapter = self.platformAdapter {
                try? boxService?.close()
                var reloadError: NSError?
                if let newService = LibboxNewService(config, adapter, &reloadError) {
                    try? newService.start()
                    self.boxService = newService
                    NSLog("[VortexExtension] Libbox service successfully reloaded with new config")
                }
            }
            #endif

            let response: [String: Any] = ["success": true]
            replyJSON(response, completionHandler: completionHandler)

        case .pingNode:
            let response: [String: Any] = ["latency": 45]
            replyJSON(response, completionHandler: completionHandler)
        }
    }

    private func replyJSON(_ dictionary: [String: Any], completionHandler: ((Data?) -> Void)?) {
        if let data = try? JSONSerialization.data(withJSONObject: dictionary) {
            completionHandler?(data)
        } else {
            completionHandler?(nil)
        }
    }

    // MARK: - Packet Loop & Fallback Flow

    private func startPacketFlowLoop() {
        guard isRunning else { return }

        packetFlow.readPackets { [weak self] packets, protocols in
            guard let self = self, self.isRunning else { return }

            for packet in packets {
                self.rxBytes += Int64(packet.count)
            }

            self.startPacketFlowLoop()
        }
    }

    private func startStatsUpdater() {
        statsTask?.cancel()
        statsTask = Task { [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(nanoseconds: 1_000_000_000)
                guard let self = self, self.isRunning else { break }

                let mem = self.getMemoryUsageBytes()
                let memMB = Double(mem) / (1024 * 1024)
                if memMB > 40.0 {
                    NSLog("[VortexExtension] WARNING: Memory usage high: %.2f MB / 50 MB", memMB)
                }
            }
        }
    }

    // MARK: - System Memory Readout (Mach Task Info)

    private func getMemoryUsageBytes() -> Int64 {
        var taskInfo = mach_task_basic_info()
        var count = mach_msg_type_number_t(MemoryLayout<mach_task_basic_info>.size / 4)
        let kerr: kern_return_t = withUnsafeMutablePointer(to: &taskInfo) {
            $0.withMemoryRebound(to: integer_t.self, capacity: 1) {
                task_info(mach_task_self_, task_flavor_t(MACH_TASK_BASIC_INFO), $0, &count)
            }
        }

        if kerr == KERN_SUCCESS {
            return Int64(taskInfo.resident_size)
        }
        return 0
    }

    // MARK: - Power Lifecycle

    public override func sleep(completionHandler: @escaping () -> Void) {
        NSLog("[VortexExtension] Extension entering sleep")
        completionHandler()
    }

    public override func wake() {
        NSLog("[VortexExtension] Extension woke up")
    }
}

// MARK: - Libbox Platform Interface Adapter

#if canImport(Libbox)
final class LibboxPlatformAdapter: NSObject, LibboxPlatformInterfaceProtocol {
    private weak var provider: NEPacketTunnelProvider?

    init(provider: NEPacketTunnelProvider) {
        self.provider = provider
        super.init()
    }

    func autoDetectControl(_ fd: Int32) throws {}

    func clearDNSCache() {}

    func closeDefaultInterfaceMonitor(_ listener: (any LibboxInterfaceUpdateListenerProtocol)?) throws {}

    func findConnectionOwner(
        _ ipProtocol: Int32,
        sourceAddress: String?,
        sourcePort: Int32,
        destinationAddress: String?,
        destinationPort: Int32,
        ret0_: UnsafeMutablePointer<Int32>?
    ) throws {}

    func getInterfaces() throws -> any LibboxNetworkInterfaceIteratorProtocol {
        return LibboxEmptyInterfaceIterator()
    }

    func includeAllNetworks() -> Bool {
        return false
    }

    func openTun(_ options: (any LibboxTunOptionsProtocol)?, ret0_: UnsafeMutablePointer<Int32>?) throws {
        if let provider = provider,
           let fd = provider.packetFlow.value(forKeyPath: "socket.fileDescriptor") as? Int32,
           fd > 0 {
            ret0_?.pointee = fd
            NSLog("[VortexExtension] Assigned utun fd %d to Libbox sing-box core", fd)
        }
    }

    func packageName(byUid uid: Int32, error: NSErrorPointer) -> String {
        return ""
    }

    func readWIFIState() -> LibboxWIFIState? {
        return nil
    }

    func send(_ notification: LibboxNotification?) throws {}

    func startDefaultInterfaceMonitor(_ listener: (any LibboxInterfaceUpdateListenerProtocol)?) throws {}

    func uid(byPackageName packageName: String?, ret0_: UnsafeMutablePointer<Int32>?) throws {}

    func underNetworkExtension() -> Bool {
        return true
    }

    func usePlatformAutoDetectControl() -> Bool {
        return false
    }

    func useProcFS() -> Bool {
        return false
    }

    func writeLog(_ message: String?) {
        if let msg = message {
            NSLog("[sing-box] %@", msg)
        }
    }
}

final class LibboxEmptyInterfaceIterator: NSObject, LibboxNetworkInterfaceIteratorProtocol {
    func hasNext() -> Bool { false }
    func next() -> LibboxNetworkInterface? { nil }
}
#endif
